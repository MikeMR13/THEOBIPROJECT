-- Sólo PostgreSQL temporal, sin acceso ni credenciales productivas.
CREATE SCHEMA auth;
CREATE SCHEMA private;
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
GRANT USAGE ON SCHEMA auth,private,public TO authenticated;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
 SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
$$;
CREATE TABLE public.teams(
 id uuid PRIMARY KEY,require_approval boolean NOT NULL DEFAULT false
);
CREATE TABLE public.series(id uuid PRIMARY KEY,team_id uuid REFERENCES public.teams(id));
CREATE TABLE public.chapters(
 id uuid PRIMARY KEY,series_id uuid REFERENCES public.series(id),
 title text NOT NULL,body jsonb NOT NULL,version integer NOT NULL DEFAULT 1,
 status text NOT NULL DEFAULT 'draft',
 deleted_at timestamptz
);
CREATE TABLE public.review_requests(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chapter_id uuid NOT NULL REFERENCES public.chapters(id),
 requested_by uuid,assigned_to uuid,note text,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','changes')),
 review_note text,approved_hash text,created_at timestamptz DEFAULT now(),reviewed_at timestamptz
);
CREATE ROLE editor_fake NOLOGIN;
CREATE FUNCTION private.series_team(p_id uuid) RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT team_id FROM public.series WHERE id=p_id
$$;
CREATE FUNCTION private.chapter_team(p_id uuid) RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT s.team_id FROM public.chapters c JOIN public.series s ON s.id=c.series_id WHERE c.id=p_id
$$;
CREATE FUNCTION private.in_team(p_team uuid) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT p_team='00000000-0000-4000-8000-000000000001'::uuid AND
  auth.uid() IN('00000000-0000-4000-8000-000000000011'::uuid,
                '00000000-0000-4000-8000-000000000012'::uuid,
                '00000000-0000-4000-8000-000000000013'::uuid)
$$;
CREATE FUNCTION private.team_can(p_team uuid,p_key text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT private.in_team(p_team) AND (
  (p_key='edit' AND auth.uid() IN('00000000-0000-4000-8000-000000000011'::uuid,'00000000-0000-4000-8000-000000000013'::uuid))
  OR (p_key='review' AND auth.uid() IN('00000000-0000-4000-8000-000000000012'::uuid,'00000000-0000-4000-8000-000000000013'::uuid))
 )
$$;
CREATE FUNCTION private.team_role_of(p_team uuid) RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT CASE WHEN p_team='00000000-0000-4000-8000-000000000001'::uuid AND
 auth.uid()='00000000-0000-4000-8000-000000000013'::uuid
 THEN 'owner' ELSE 'editor' END
$$;
